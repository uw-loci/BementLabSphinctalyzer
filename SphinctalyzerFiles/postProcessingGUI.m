function postProcessingGUI(selpaths)
    numSelPaths = length(selpaths);
    imgarray(1:numSelPaths) = Image(0,1,0,3,1,1,3,0,8,0,0, ...
                'gray',6,{'Distance (microns) from wound center','Normalized Gray Value'}, ...
                [-150 50 0] * 0.192,[-0.1 0.3 1.1],1,0.192,"",0,0, ...
                {[1 0 0],[0 .6 0],[0 0 1]},0,'NorthWest',1,'', {}, [1 2]);
    for i = 1:numSelPaths
        try
            load(fullfile(selpaths{i},'parameters.mat'));
        catch
            error('PLEASE SELECT A VALID DATA FOLDER.');
        end
        imgarray(i) = Image(parameters.cellArray, ...
            parameters.timepointStart, ...
            parameters.timepointEnd, ...
            parameters.speed, ...
            parameters.loadMulti, ...
            parameters.shape, ...
            parameters.detection, ...
            parameters.smooth, ...
            parameters.step, ...
            parameters.filePath, ...
            parameters.nTimepoints, ...
            parameters.colormap, ...
            parameters.timePerFrame, ...
            parameters.axesNames, ...
            parameters.xMinStepMax, ...
            parameters.yMinStepMax, ...
            parameters.normalization, ...
            parameters.micronsPerPixel, ...
            parameters.imagePath, ...
            parameters.imageName, ...
            parameters.channelNames, ...
            parameters.channelColors, ...
            parameters.darkBackground, ...
            parameters.legendLocation, ...
            parameters.roiShape, ...
            '', ...
            parameters.moviePaths, ...
            parameters.velocityStartStop);
        imgarray(i).nChannels = parameters.nChannels;
    end
    objarray = imgarray;
    sphinctalyzerOutput(objarray)