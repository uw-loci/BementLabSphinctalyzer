    %% Sphinctalyze Initialize for Batch Processing
    function sphinctalyzeBatchInitialize(hObject,eventdata,handles)
        set(hObject,'Enable','off')
        if control.nChannels == 1
            cellArray = {cellInputs.RowName{1}, cellInputs.Data{1, :}};
            channelNames = cellInputs.RowName{1};
        elseif control.nChannels == 2
            cellArray = {cellInputs.RowName{1}, cellInputs.Data{1, :}; cellInputs.RowName{2}, cellInputs.Data{2, :}};
            channelNames = {cellInputs.RowName{1}, cellInputs.RowName{2}};
        else
            error("not supported yet")
        end
            control.iTimepoint = control.start;
        file = SphinctalyzerInitializer(cellArray,control.start, ...
            control.end, ...
            get(enterSpeed,'UserData'), ...
            get(loadMulti, 'Value'),...
            get(enterShape,'UserData'), ...
            get(enterDetection, 'UserData'), ...
            get(enterSmooth,'UserData'), ...
            get(enterStep,'UserData'),...
            control.imagePath, ...
            control.imageName,control.colormap, ...
            get(roiSelection,'Value'), ...
            getappdata(guiCtrl,'batchDirectory'));

        % instantiate object with attributes
        currentImage = getappdata(guiCtrl,'currentImage');
        fileNames = getappdata(guiCtrl,'fileNames');
        objarray = getappdata(guiCtrl,'imageObjects');
        objarray(currentImage) = Image(cellArray,control.start, ...
            control.end, ...
            get(enterSpeed,'UserData'), ...
            get(loadMulti, 'Value'),...
            get(enterShape,'UserData'), ...
            get(enterDetection, 'UserData'), ...
            get(enterSmooth,'UserData'), ...
            get(enterStep,'UserData'),...
            file, ...
            control.nTimepoints,control.colormap, ...
            getappdata(guiCtrl,'timePerFrame'), ...
            getappdata(guiCtrl,'axesNames'), ...
            getappdata(guiCtrl,'xMinStepMax'), ...
            getappdata(guiCtrl,'yMinStepMax'), ...
            get(enterNormalization,'UserData'), ...
            get(enterMicronsPerPixel,'UserData'), ...
            control.imagePath, ...
            control.imageName, ...
            channelNames);
        setappdata(guiCtrl,'imageObjects',objarray)
        if currentImage == length(fileNames)
            delete(hObject);
            delete(handles);
            sphinctalyze()
        else
            currentImage = currentImage + 1;
            setappdata(guiCtrl,'currentImage',currentImage)
            fileName = fileNames{currentImage};
            pathName = control.imagePath;
            ff = fullfile(pathName,fileName);
         Img = imread(ff);
         r = bfGetReader(ff);
         seriesCount = r.getSeriesCount();
         nChannels = r.getSizeC(); 
         nTimepoints = r.getSizeT(); 
         nFocalplanes = r.getSizeZ(); 
         control.imagePath = pathName;
         control.imageName = fileName;
         control.seriesCount = seriesCount;
         control.nTimepoints = nTimepoints;
         control.nChannels = nChannels;
         control.Focalplanes = nFocalplanes;
         control.iSeries = seriesCount;
         handles.Data{1} = fileName;
         handles.Data{2} = nTimepoints;
         for i = 1:nChannels
             cellInputs.RowName{i, 1} = "channel" + i;
             cellInputs.Data{i, 1} = 1;
             if i ~= 1
                 cellInputs.Data{i, 2} = 0;
             else 
                 cellInputs.Data{i, 2} = 1;
             end
         end
         set(hObject,'Enable','on')
        end
    end

    %% Sphinctalyze 
    function sphinctalyze(hObject,eventdata)
