            if control.nChannels == 1
                cellArray = {cellInputs.RowName{1}, cellInputs.Data{1, :}};
                channelNames = cellInputs.RowName{1};
            elseif control.nChannels == 2
                cellArray = {cellInputs.RowName{1}, cellInputs.Data{1, :}; cellInputs.RowName{2}, cellInputs.Data{2, :}};
                channelNames = {cellInputs.RowName{1}, cellInputs.RowName{2}};
            else
                error("not supported yet")
            end
            control.iTimepoint = control.start;
    
            file = SphinctalyzerInitializer(cellArray,control.start, ...
                control.end, ...
                get(enterSpeed,'UserData'), ...
                get(loadMulti, 'Value'),...
                get(enterShape,'UserData'), ...
                get(enterDetection, 'UserData'), ...
                get(enterSmooth,'UserData'), ...
                get(enterStep,'UserData'),...
                control.imagePath, ...
                control.imageName,control.colormap, ...
                get(roiSelection,'Value'), ...
                '');
            
            [ParentFolderPath] = fileparts(file);
            [ParentFolderPath] = fileparts(ParentFolderPath);
            SphincRescue(ParentFolderPath)
            
            % loop through each data folder and input object attributes
    
            setappdata(guiCtrl,'channelColors',{[1 0 0],[0 .6 0],[0 0 1]})
            setappdata(guiCtrl,'darkBackgroundFlag',0)
            setappdata(guiCtrl,'legendLocation','NorthWest')
    
            SphinctalyzerMoviePlotterMulti(ParentFolderPath, ...
                getappdata(guiCtrl,'channelColors'), ...
                getappdata(guiCtrl,'axesNames'), ...
                getappdata(guiCtrl,'darkBackgroundFlag'), ...
                getappdata(guiCtrl,'timePerFrame'), ...
                get(enterNormalization,'UserData'), ...
                getappdata(guiCtrl,'legendLocation'), ...
                get(enterMicronsPerPixel,'UserData'), ...
                getappdata(guiCtrl,'xMinStepMax'), ...
                getappdata(guiCtrl,'yMinStepMax'))
            
            moviePlayer(strcat(ParentFolderPath,'/sphincRedo/scan movietalyzerResults.avi'), control.start, control.nTimepoints)
    
            SphinctalyzerImageSlider(control, channelNames, ParentFolderPath, getappdata(guiCtrl, 'timePerFrame'))

            moviePlotOptions = uipanel('Parent',guiCtrl, ...
                'Title','Movie Plot Options', ...
                'Units','normalized', ...
                'Position',[0 0.06 1 0.32]);
            
            changeXAxis = uicontrol('Parent',moviePlotOptions, ...
                'Style','pushbutton', ...
                'String','Edit X Axis', ...
                'FontSize',10, ...
                'Units','normalized', ...
                'Position',[0.1 0.9 .35 .075], ...
                'Callback',{@change_x_axis});
            
