function postProcessingGUI
    % prompt user to load a directoy
    % if a batch directory, then load both (somehow?)
    % if a single directory, should be pretty simple..
    % USE PARAMETERS.MAT
    if ~isdeployed
        addpath(genpath(fullfile('./../bfmatlab')));
    end

    selpath = uigetdir('~');
    if isequal(selpath, 0)
        return
    else
        addpath(selpath);
    end

    try
        load('parameters.mat');
    catch
        rmpath(selpath)
        error('PLEASE SELECT A VALID DATA FOLDER.');
    end
    rmpath(selpath)
    imgarray(1) = Image(parameters.cellArray, ...
        parameters.timepointStart, ...
        parameters.timepointEnd, ...
        parameters.speed, ...
        parameters.loadMulti, ...
        parameters.shape, ...
        parameters.detection, ...
        parameters.smooth, ...
        parameters.step, ...
        parameters.filePath, ...
        parameters.nTimepoints, ...
        parameters.colormap, ...
        parameters.timePerFrame, ...
        parameters.axesNames, ...
        parameters.xMinStepMax, ...
        parameters.yMinStepMax, ...
        parameters.normalization, ...
        parameters.micronsPerPixel, ...
        parameters.imagePath, ...
        parameters.imageName, ...
        parameters.channelNames, ...
        parameters.channelColors, ...
        parameters.darkBackground, ...
        parameters.legendLocation, ...
        parameters.roiShape, ...
        '', ...
        parameters.moviePaths, ...
        parameters.velocityStartStop);
    imgarray(1).nChannels = parameters.nChannels;
    objarray = imgarray;
    sphinctalyzerOutput(objarray)